export function addLabels(lang: string, labels: Record<string, string>) {
  L[lang] = { ...(L[lang] ?? {}), ...labels };
}

export function labels(lang = 'en') {
  const base = L.en;
  const l = L[lang.slice(0, 2).toLowerCase()] ?? {};
  return (key: string) => l[key] ?? base[key] ?? key;
}
